import assert from 'node:assert/strict';
import { rsi, macd, sma, volatility, maxDrawdown } from './indicators.js';
const up = Array.from({ length: 60 }, (_, i) => 100 + i);
const dn = up.slice().reverse();
assert.equal(rsi(up), 100);
assert.ok(rsi(dn) < 1);
assert.ok(macd(up).macd > 0);
assert.equal(sma([1, 2, 3, 4], 2), 3.5);
assert.ok(volatility(up).daily > 0);
assert.equal(Math.round(maxDrawdown([100, 50, 75])), -50);
console.log('indicators: OK');
